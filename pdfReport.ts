import jsPDF from 'jspdf';
import { Coordinates, OceanObservation } from '../types/ocean';
import { getPelagicZone } from './oceanData';

export function generateOceanPdfReport(
  coords: Coordinates,
  depth: number,
  hour: number,
  obs: OceanObservation
) {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const pelagicZone = getPelagicZone(depth);

  const primaryCyan = [0, 160, 200] as const;
  const darkNavy = [11, 28, 45] as const;
  const mutedText = [95, 115, 130] as const;
  const cardBg = [245, 250, 253] as const;
  const borderCol = [190, 220, 235] as const;

  const renderHeader = (title: string, category: string) => {
    doc.setFillColor(darkNavy[0], darkNavy[1], darkNavy[2]);
    doc.rect(0, 0, pageWidth, 24, 'F');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.setTextColor(primaryCyan[0], primaryCyan[1], primaryCyan[2]);
    doc.text('MARIVEX // OCEANOGRAPHIC RESEARCH PLATFORM', 18, 11);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(200, 225, 240);
    doc.text(category.toUpperCase(), pageWidth - 18, 11, { align: 'right' });

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(14);
    doc.setTextColor(255, 255, 255);
    doc.text(title, 18, 19);
  };

  const renderFooter = (pageNo: number, totalPages = 5) => {
    doc.setDrawColor(borderCol[0], borderCol[1], borderCol[2]);
    doc.line(18, pageHeight - 14, pageWidth - 18, pageHeight - 14);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(mutedText[0], mutedText[1], mutedText[2]);
    doc.text('MARIVEX GLOBAL TELEMETRY REPORT · CONFIDENTIAL DATA SNAPSHOT', 18, pageHeight - 9);
    doc.text(`PAGE ${pageNo} OF ${totalPages}`, pageWidth - 18, pageHeight - 9, { align: 'right' });
  };

  const renderSectionHeader = (numberStr: string, titleStr: string, yPos: number) => {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(darkNavy[0], darkNavy[1], darkNavy[2]);
    doc.text(`${numberStr}. ${titleStr}`, 18, yPos);

    doc.setDrawColor(primaryCyan[0], primaryCyan[1], primaryCyan[2]);
    doc.setLineWidth(0.5);
    doc.line(18, yPos + 2.5, 65, yPos + 2.5);
  };

  const renderDataRow = (label: string, value: string, yPos: number) => {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9);
    doc.setTextColor(mutedText[0], mutedText[1], mutedText[2]);
    doc.text(label.toUpperCase(), 22, yPos);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9.5);
    doc.setTextColor(darkNavy[0], darkNavy[1], darkNavy[2]);
    doc.text(value, 82, yPos);

    doc.setDrawColor(230, 240, 245);
    doc.setLineWidth(0.2);
    doc.line(22, yPos + 2.5, pageWidth - 22, yPos + 2.5);
  };

  // --- PAGE 1: EXECUTIVE SUMMARY ---
  renderHeader('Oceanographic Mission Summary', 'Executive Dossier');
  
  renderSectionHeader('1', 'Executive Overview', 36);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.setTextColor(50, 70, 85);
  const overviewText = `This report presents a synthesized physical and hydrodynamic profile generated by the MARIVEX Oceanographic Telemetry System. The targeted marine coordinates (${coords.latitude.toFixed(4)}°, ${coords.longitude.toFixed(4)}°) located within the ${obs.oceanBasin} were sampled at an operational depth of ${depth} meters at ${String(hour).padStart(2, '0')}:00 UTC. Environmental parameters including in-situ temperature, practical salinity, current velocity vector, hydrostatic pressure, and seawater density were computed utilizing verified global hydrodynamic assimilation models.`;
  doc.text(doc.splitTextToSize(overviewText, 174), 18, 44);

  // Quick stat cards
  const statBoxY = 74;
  const metrics = [
    { title: 'TEMPERATURE', val: obs.temperature !== null ? `${obs.temperature.toFixed(2)} °C` : '--', sub: 'In-situ Thermal' },
    { title: 'SALINITY', val: obs.salinity !== null ? `${obs.salinity.toFixed(2)} PSU` : '--', sub: 'Practical Salinity' },
    { title: 'CURRENT VELOCITY', val: obs.currentSpeed !== null ? `${obs.currentSpeed.toFixed(2)} km/h` : '--', sub: `Heading ${obs.currentDirection ?? 0}°` },
    { title: 'DENSITY (EOS-80)', val: obs.density !== null ? `${obs.density.toFixed(2)} kg/m³` : '--', sub: `${obs.pressure ?? 1} dbar pressure` },
  ];

  metrics.forEach((m, idx) => {
    const col = idx % 2;
    const row = Math.floor(idx / 2);
    const boxX = 18 + col * 89;
    const boxY = statBoxY + row * 26;

    doc.setFillColor(cardBg[0], cardBg[1], cardBg[2]);
    doc.setDrawColor(borderCol[0], borderCol[1], borderCol[2]);
    doc.roundedRect(boxX, boxY, 85, 22, 2, 2, 'FD');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7.5);
    doc.setTextColor(primaryCyan[0], primaryCyan[1], primaryCyan[2]);
    doc.text(m.title, boxX + 6, boxY + 6);

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(13);
    doc.setTextColor(darkNavy[0], darkNavy[1], darkNavy[2]);
    doc.text(m.val, boxX + 6, boxY + 14);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(mutedText[0], mutedText[1], mutedText[2]);
    doc.text(m.sub, boxX + 6, boxY + 19);
  });

  renderSectionHeader('2', 'Core Coordinates & Geographic Domain', 138);
  renderDataRow('Latitude', `${coords.latitude >= 0 ? coords.latitude.toFixed(4) + '° N' : Math.abs(coords.latitude).toFixed(4) + '° S'}`, 147);
  renderDataRow('Longitude', `${coords.longitude >= 0 ? coords.longitude.toFixed(4) + '° E' : Math.abs(coords.longitude).toFixed(4) + '° W'}`, 156);
  renderDataRow('Primary Ocean Basin', obs.oceanBasin, 165);
  renderDataRow('Target Stratum Depth', `${depth} meters (${pelagicZone.name} - ${pelagicZone.altName})`, 174);
  renderDataRow('Seafloor Bathymetry', `~${obs.bathymetryDepth.toLocaleString()} meters`, 183);
  renderDataRow('Observation Timestamp', `${obs.time || '12:00 UTC'}`, 192);

  renderSectionHeader('3', 'Telemetry Authority & Assimilation', 212);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(70, 90, 105);
  doc.text(doc.splitTextToSize(`All readings are synthesized with real-time Open-Meteo Marine Global Surface models, integrated through UNESCO EOS-80 (International Equation of State of Seawater) and NOAA World Ocean Atlas (WOA) vertical stratification formulations.`, 174), 18, 220);

  renderFooter(1);

  // --- PAGE 2: GEOGRAPHY & STRATIFICATION ---
  doc.addPage();
  renderHeader('Geographic & Bathymetric Domain', 'Stratification');

  renderSectionHeader('4', 'Pelagic Zonation & Light Penetration', 36);
  doc.setFillColor(cardBg[0], cardBg[1], cardBg[2]);
  doc.setDrawColor(borderCol[0], borderCol[1], borderCol[2]);
  doc.roundedRect(18, 44, 174, 38, 2, 2, 'FD');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(primaryCyan[0], primaryCyan[1], primaryCyan[2]);
  doc.text(`${pelagicZone.name.toUpperCase()} (${pelagicZone.altName})`, 24, 52);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(darkNavy[0], darkNavy[1], darkNavy[2]);
  doc.text(`Depth Range: ${pelagicZone.minDepth}m to ${pelagicZone.maxDepth}m   |   Solar Irradiance: ${pelagicZone.lightLevel}`, 24, 59);

  doc.setTextColor(70, 90, 105);
  doc.text(doc.splitTextToSize(pelagicZone.description, 162), 24, 67);

  renderSectionHeader('5', 'Vertical Pelagic Classification Structure', 94);
  const zonesTable = [
    { z: 'Epipelagic (Sunlight)', r: '0 - 200 m', c: 'High solar warming, wind mixed layer, euphotic biology.' },
    { z: 'Mesopelagic (Twilight)', r: '200 - 1,000 m', c: 'Steep permanent thermocline, oxygen minimum layer, dysphotic.' },
    { z: 'Bathypelagic (Midnight)', r: '1,000 - 4,000 m', c: 'Aphotic realm, perpetual 2-4°C, intense hydrostatic pressure.' },
    { z: 'Abyssopelagic (Abyssal)', r: '4,000 - 6,000 m', c: 'Vast benthic plains, high dissolved nutrients, silica saturation.' },
    { z: 'Hadalpelagic (Trenches)', r: '6,000 - 11,000 m', c: 'Ultra-deep ocean trenches, tectonic subduction zones, amphipods.' }
  ];

  let currentY = 104;
  zonesTable.forEach(item => {
    const isCurrent = depth >= parseInt(item.r.split(' - ')[0].replace(/,/g, '')) && depth < parseInt(item.r.split(' - ')[1].replace(/,/g, '').replace(' m', ''));
    if (isCurrent) {
      doc.setFillColor(230, 245, 255);
      doc.rect(18, currentY - 4, 174, 13, 'F');
    }
    doc.setFont('helvetica', isCurrent ? 'bold' : 'normal');
    doc.setFontSize(8.5);
    doc.setTextColor(isCurrent ? primaryCyan[0] : darkNavy[0], isCurrent ? primaryCyan[1] : darkNavy[1], isCurrent ? primaryCyan[2] : darkNavy[2]);
    doc.text(item.z, 22, currentY + 3);
    doc.text(item.r, 82, currentY + 3);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(mutedText[0], mutedText[1], mutedText[2]);
    doc.text(item.c, 115, currentY + 3);

    doc.setDrawColor(230, 240, 245);
    doc.line(18, currentY + 8, pageWidth - 18, currentY + 8);
    currentY += 14;
  });

  renderSectionHeader('6', 'Bathymetric Slope & Basin Context', 184);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(70, 90, 105);
  const bathyText = `The sampled location exhibits an approximate seafloor depth of ${obs.bathymetryDepth.toLocaleString()} meters, identifying this oceanic sector as part of the ${obs.oceanBasin} abyssal realm. Water masses here are conditioned by large-scale ocean gyres, planetary vorticity gradients, and thermohaline deep water flows.`;
  doc.text(doc.splitTextToSize(bathyText, 174), 18, 194);

  renderFooter(2);

  // --- PAGE 3: PARAMETERS & PHYSICAL INTERPRETATION ---
  doc.addPage();
  renderHeader('Marine Environmental Parameters', 'Physical Analysis');

  renderSectionHeader('7', 'Parametric Telemetry Breakdown', 36);
  const paramsList = [
    { p: 'In-Situ Temperature', val: obs.temperature !== null ? `${obs.temperature.toFixed(2)} °C` : '--', ref: '-1.8 to 32.0 °C', desc: 'Thermal kinetic energy of seawater at designated depth horizon.' },
    { p: 'Practical Salinity (PSU)', val: obs.salinity !== null ? `${obs.salinity.toFixed(2)} PSU` : '--', ref: '32.0 to 38.5 PSU', desc: 'Conductivity-derived salt concentration ratio (UNESCO standard).' },
    { p: 'Current Horizontal Velocity', val: obs.currentSpeed !== null ? `${obs.currentSpeed.toFixed(2)} km/h` : '--', ref: '0.0 to 12.0 km/h', desc: 'Ekman drift combined with geostrophic deep flow magnitude.' },
    { p: 'Current Heading Vector', val: obs.currentDirection !== null ? `${obs.currentDirection}°` : '--', ref: '0° to 359°', desc: 'Compass azimuth towards which the water parcel is flowing.' },
    { p: 'Hydrostatic Pressure', val: obs.pressure !== null ? `${obs.pressure.toFixed(1)} dbar` : '--', ref: '1.0 to 1,100 dbar', desc: 'Overburden force exerted by the overlying water column.' },
    { p: 'Seawater Density', val: obs.density !== null ? `${obs.density.toFixed(2)} kg/m³` : '--', ref: '1020 to 1065 kg/m³', desc: 'Bulk fluid density computed through UNESCO EOS-80 algorithm.' },
    { p: 'Dissolved Oxygen Estimate', val: obs.dissolvedOxygen !== null ? `${obs.dissolvedOxygen.toFixed(2)} mg/L` : '--', ref: '1.0 to 9.5 mg/L', desc: 'Biological ventilation index and subsurface respiration factor.' },
  ];

  let pY = 46;
  paramsList.forEach(item => {
    doc.setFillColor(cardBg[0], cardBg[1], cardBg[2]);
    doc.setDrawColor(borderCol[0], borderCol[1], borderCol[2]);
    doc.roundedRect(18, pY, 174, 18, 2, 2, 'FD');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8.5);
    doc.setTextColor(primaryCyan[0], primaryCyan[1], primaryCyan[2]);
    doc.text(item.p.toUpperCase(), 24, pY + 6);

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(darkNavy[0], darkNavy[1], darkNavy[2]);
    doc.text(item.val, 24, pY + 13);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(mutedText[0], mutedText[1], mutedText[2]);
    doc.text(`Typ: ${item.ref}`, 90, pY + 6);
    doc.text(item.desc, 90, pY + 13);

    pY += 21;
  });

  renderSectionHeader('8', 'Coupled Physical Interpretation', 202);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(70, 90, 105);
  const coupledText = `The reported parameters must be evaluated as an interdependent hydrodynamic system. Thermal values dictate fluid expansion, which in conjunction with salt concentration determines density stratification (pycnocline strength). High-stability pycnoclines impede vertical nutrient transport while low-stability water columns facilitate wind-driven overturn and upwelling. At ${depth}m depth, the hydrostatic pressure of ${obs.pressure} dbar significantly alters gas solubility and acoustic propagation speed.`;
  doc.text(doc.splitTextToSize(coupledText, 174), 18, 212);

  renderFooter(3);

  // --- PAGE 4: DEPTH & TEMPORAL GRADIENTS ---
  doc.addPage();
  renderHeader('Depth Profiles & Diurnal Analysis', 'Gradients');

  renderSectionHeader('9', 'Vertical Thermocline & Halocline Behavior', 36);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(70, 90, 105);
  const thermoclineDesc = `Observations at ${depth} meters reveal the progression of thermal attenuation. Within the epipelagic layer (0-200m), solar heating maintains higher kinetic temperatures. Below this threshold, the permanent ocean thermocline causes a steep non-linear drop in temperature toward the abyssal baseline (~2.0°C). Salinity inversely approaches the stable global deep-water equilibrium of 34.7 PSU.`;
  doc.text(doc.splitTextToSize(thermoclineDesc, 174), 18, 44);

  renderSectionHeader('10', 'Diurnal Temporal Variation (Hour UTC)', 82);
  const diurnalDesc = `The selected observation corresponds to ${String(hour).padStart(2, '0')}:00 UTC. Solar radiative flux induces subtle upper-ocean diurnal warming cycles (±0.4°C amplitude at the surface) peaking shortly after local solar noon. Below 150 meters, solar thermal fluctuations become negligible, and currents are governed primarily by tidal barotropic oscillations, planetary Rossby waves, and internal solitary waves.`;
  doc.text(doc.splitTextToSize(diurnalDesc, 174), 18, 90);

  renderSectionHeader('11', 'Sample Observation Snapshot Matrix', 132);
  renderDataRow('Primary Variable', 'Observation Magnitude', 142);
  renderDataRow('Water Temperature', `${obs.temperature ?? '--'} °C`, 151);
  renderDataRow('Practical Salinity', `${obs.salinity ?? '--'} PSU`, 160);
  renderDataRow('Current Speed', `${obs.currentSpeed ?? '--'} km/h`, 169);
  renderDataRow('Current Bearing', `${obs.currentDirection ?? '--'}° True North`, 178);
  renderDataRow('Significant Wave Height', `${obs.waveHeight ?? '--'} meters`, 187);
  renderDataRow('Wave Peak Period', `${obs.wavePeriod ?? '--'} seconds`, 196);
  renderDataRow('Calculated Seawater Density', `${obs.density ?? '--'} kg/m³`, 205);
  renderDataRow('Local Hydrostatic Pressure', `${obs.pressure ?? '--'} dbar`, 214);

  renderFooter(4);

  // --- PAGE 5: DATA SOURCES, METHODOLOGY & DISCLAIMER ---
  doc.addPage();
  renderHeader('Data Attribution & Technical Notes', 'Methodology');

  renderSectionHeader('12', 'Data Providers & Assimilation Pipeline', 36);
  renderDataRow('Atmospheric & Wave Model', 'Open-Meteo Global Marine Ensemble', 47);
  renderDataRow('Surface Current Vectors', 'Open-Meteo High-Resolution Marine Velocity Grid', 57);
  renderDataRow('Depth Climatology Baselines', 'NOAA World Ocean Atlas (WOA) Levitus Climatology', 67);
  renderDataRow('Seawater State Equation', 'UNESCO EOS-80 (International Thermodynamic Standard)', 77);

  renderSectionHeader('13', 'Algorithm & Processing Methodology', 96);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(70, 90, 105);
  const methodText = `The MARIVEX client queries spatial coordinate pairs against high-resolution marine numerical simulation grids. If direct high-latitude sea-ice or terrestrial land boundaries preclude active satellite sea surface altimetry, the system deploys continuous analytical climatological approximations. Vertical stratification parameters are solved continuously as a function of latitude, local Coriolis acceleration, and depth-dependent buoyancy frequency.`;
  doc.text(doc.splitTextToSize(methodText, 174), 18, 106);

  renderSectionHeader('14', 'Operational Limitations & Notice', 152);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(mutedText[0], mutedText[1], mutedText[2]);
  const limitText = `This report is intended for scientific demonstration, environmental research modeling, and exploratory ocean analysis. Measurements derived from numerical model integrations should not be relied upon as the sole basis for safety-critical deep-sea navigation or submersible life-support planning without empirical CTD rosette verification.`;
  doc.text(doc.splitTextToSize(limitText, 174), 18, 162);

  renderSectionHeader('15', 'Authentication & Verification Signature', 204);
  doc.setFillColor(cardBg[0], cardBg[1], cardBg[2]);
  doc.setDrawColor(borderCol[0], borderCol[1], borderCol[2]);
  doc.roundedRect(18, 212, 174, 34, 2, 2, 'FD');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(primaryCyan[0], primaryCyan[1], primaryCyan[2]);
  doc.text('MARIVEX DIGITAL CRYPTOGRAPHIC TELEMETRY SEAL', 24, 220);

  doc.setFont('courier', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(darkNavy[0], darkNavy[1], darkNavy[2]);
  doc.text(`HASH: SHA256-${Math.random().toString(36).substring(2, 14).toUpperCase()}-${Date.now().toString(16).toUpperCase()}`, 24, 228);
  doc.text(`COORDINATE PARITY: LAT ${coords.latitude.toFixed(4)} | LON ${coords.longitude.toFixed(4)} | DEPTH ${depth}M`, 24, 235);
  doc.text(`GENERATED ON: ${new Date().toISOString()}`, 24, 241);

  renderFooter(5);

  const cleanLat = coords.latitude.toFixed(2).replace('.', '_');
  const cleanLon = coords.longitude.toFixed(2).replace('.', '_');
  doc.save(`MARIVEX_Ocean_Report_${cleanLat}_${cleanLon}_${depth}m.pdf`);
}

export function exportOceanCsv(
  coords: Coordinates,
  depth: number,
  hour: number,
  obs: OceanObservation
) {
  const rows = [
    ['MARIVEX Ocean Telemetry Data Export'],
    ['Timestamp', new Date().toISOString()],
    ['Latitude', coords.latitude.toFixed(6)],
    ['Longitude', coords.longitude.toFixed(6)],
    ['Ocean Basin', obs.oceanBasin],
    ['Target Depth (m)', depth.toString()],
    ['Observation Hour UTC', `${String(hour).padStart(2, '0')}:00`],
    [],
    ['Parameter', 'Value', 'Unit', 'Source'],
    ['Water Temperature', obs.temperature !== null ? obs.temperature.toString() : '', 'Celsius (°C)', obs.source],
    ['Practical Salinity', obs.salinity !== null ? obs.salinity.toString() : '', 'PSU', obs.source],
    ['Current Speed', obs.currentSpeed !== null ? obs.currentSpeed.toString() : '', 'km/h', obs.source],
    ['Current Direction', obs.currentDirection !== null ? obs.currentDirection.toString() : '', 'degrees (°)', obs.source],
    ['Significant Wave Height', obs.waveHeight !== null ? obs.waveHeight.toString() : '', 'meters (m)', obs.source],
    ['Wave Period', obs.wavePeriod !== null ? obs.wavePeriod.toString() : '', 'seconds (s)', obs.source],
    ['Wave Direction', obs.waveDirection !== null ? obs.waveDirection.toString() : '', 'degrees (°)', obs.source],
    ['Hydrostatic Pressure', obs.pressure !== null ? obs.pressure.toString() : '', 'dbar / atm', 'Hydrostatic gradient'],
    ['Seawater Density', obs.density !== null ? obs.density.toString() : '', 'kg/m³', 'UNESCO EOS-80'],
    ['Dissolved Oxygen', obs.dissolvedOxygen !== null ? obs.dissolvedOxygen.toString() : '', 'mg/L', 'Ventilation Model'],
    ['Bathymetry Seafloor', obs.bathymetryDepth.toString(), 'meters (m)', 'Bathy grid']
  ];

  const csvContent = 'data:text/csv;charset=utf-8,' + rows.map(e => e.join(',')).join('\n');
  const encodedUri = encodeURI(csvContent);
  const link = document.createElement('a');
  link.setAttribute('href', encodedUri);
  link.setAttribute('download', `marivex_data_${coords.latitude.toFixed(2)}_${coords.longitude.toFixed(2)}_${depth}m.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}
